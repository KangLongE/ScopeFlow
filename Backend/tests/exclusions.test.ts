import assert from "node:assert/strict";
import test from "node:test";
import { extractExclusions, prepareExclusions, editExclusions, publicExclusions, requireExclusionsReviewed, carryExclusions, sameExclusion, type ExclusionReview } from "@/lib/scope-exclusions";
const request = { id: "request:local", kind: "REQUEST", label: "고객 원문", revision: "r1", text: "결제·회원가입·관리자 페이지·외부 서비스 연동은 제외합니다. 로고는 고객이 제공합니다." };
const answer = { id: "answer:local", kind: "ANSWER", label: "저장된 고객 답변", revision: "r1", text: "배포 방법은?\nVercel 정적 배포이며 별도 서버 구현은 제외합니다." };
const sources = [request, answer];
const confirm = (review: ExclusionReview) => ({ ...review, items: review.items.map(i => ({ ...i, state: "active" as const })) });
test("EXC-01~07/10: literal suggestions, provenance and conservative semantic matching", () => {
  const review = prepareExclusions(sources, [], null);
  assert.equal(review.items.length, 5); assert.equal(review.items.filter(i => i.origin === "customer_request").length, 4);
  assert.equal(review.items.find(i => i.origin === "customer_answer")?.title, "별도 서버 구현 제외");
  assert.ok(review.items.every(i => i.explicit && i.state === "pending" && i.evidence[0].revision === "r1"));
  assert.equal(extractExclusions([{ ...request, text: "결제는 제외하지 않습니다. 로고를 제공하고 1페이지에 메뉴를 표시합니다. Vercel 배포를 사용합니다." }]).length, 0);
  assert.equal(extractExclusions([{ ...request, text: "결제 오류는 없습니다. 관리자 계정은 없습니다." }]).length, 0);
  const pending = extractExclusions([{ ...request, text: "관리자 기능은 나중에 논의하겠습니다. 유지보수 제외." }]);
  assert.equal(pending.length, 2); assert.ok(pending.every(i => !i.explicit));
  assert.equal(sameExclusion("외부 서비스 연동 개발 제외", "외부 서비스 이용료 제외"), false);
  assert.equal(sameExclusion("결제 기능 구현 제외", "결제 수수료 제외"), false);
  assert.equal(sameExclusion("회원가입 제외", "로그인 및 인증 제외"), false);
  assert.equal(sameExclusion("관리자 페이지 개발 제외", "관리자 화면 제외"), true);
  const repeated = prepareExclusions([...sources, { ...answer, text: "추가 확인\n결제 기능은 제외합니다." }], [], null);
  assert.equal(repeated.items.length, 5); assert.equal(repeated.items.find(i => i.title.startsWith("결제"))?.sourceRefs.length, 2);
  assert.deepEqual(prepareExclusions([], [], null).items, []);
  const denied = { ...request, text: "결제는 제외하지 않습니다." };
  const mistaken = prepareExclusions([denied], [{ title: "결제 기능 구현 제외", status: "explicit", sourceRefs: [denied.id], evidence: denied.text }], null);
  assert.equal(mistaken.items[0].explicit, false);
  const dismissed = editExclusions(mistaken, { ...mistaken, items: mistaken.items.map(i => ({ ...i, state: "dismissed", resolutionReason: "부정 표현을 제외로 잘못 추출함" })) }, [denied], "owner");
  assert.equal(dismissed.items[0].state, "dismissed");
  const runId = crypto.randomUUID();
  const extracted = prepareExclusions(sources, [{ title: "결제", status: "explicit", evidence: request.text, sourceRefs: [request.id], extractionRunId: runId }], null);
  assert.deepEqual(extracted.items.find(i => i.title.startsWith("결제"))?.extractionRunIds, [runId]);
  const staffSource = { id: "requirement:local", kind: "EXCLUDED_REQUIREMENT", label: "담당자 제외", revision: "r1", text: "별도 운영 작업\n담당자가 별도 범위로 분류함" };
  const staff = prepareExclusions([staffSource], [{ title: "별도 운영 작업", evidence: staffSource.text, sourceRefs: [staffSource.id] }], null);
  assert.equal(staff.items[0].origin, "staff"); assert.equal(staff.items[0].sourceRefs[0], staffSource.id);
});
test("EXC-08~09/12/14~15: edits retain evidence, reject disappearance, spoofing and stale revisions", () => {
  const review = prepareExclusions(sources, [], null);
  assert.throws(() => requireExclusionsReviewed(review, { excluded: [] }), { code: "EXCLUSIONS_REVIEW_REQUIRED" });
  const confirmed = editExclusions(review, confirm(review), sources, "owner");
  assert.ok(confirmed.items.every(i => i.reviewedBy === "owner" && i.reviewedAt));
  const document = { exclusions: publicExclusions(confirmed), excluded: publicExclusions(confirmed).map(i => i.title) };
  requireExclusionsReviewed(confirmed, document);
  assert.throws(() => editExclusions(confirmed, confirm(review), sources, "owner"), { code: "EXCLUSIONS_CHANGED" });
  const remove = structuredClone(confirmed); remove.items.pop();
  assert.throws(() => editExclusions(confirmed, remove, sources, "owner"), { code: "EXCLUSION_REMOVED" });
  for (const mutate of [(r: ExclusionReview) => { r.items[0].origin = "staff"; }, (r: ExclusionReview) => { r.items[0].sourceRefs = ["answer:foreign"]; }, (r: ExclusionReview) => { r.items[0].title = "결제 수수료 제외"; r.items[0].resolutionReason = "표현 변경"; }, (r: ExclusionReview) => { r.items[0].state = "dismissed"; r.items[0].resolutionReason = "삭제"; }]) {
    const input = structuredClone(confirmed); mutate(input); assert.throws(() => editExclusions(confirmed, input, sources, "owner"), { code: "INVALID_EXCLUSION" });
  }
  const changed = prepareExclusions([{ ...request, revision: "r2" }, answer], [], confirmed);
  assert.throws(() => editExclusions(changed, confirmed, sources, "owner"), { code: "EXCLUSIONS_CHANGED" });
  const provenance = structuredClone(confirmed); provenance.items[0].extractionRunIds = [crypto.randomUUID()];
  assert.throws(() => editExclusions(confirmed, provenance, sources, "owner"), { code: "INVALID_EXCLUSION" });
  const legacy = prepareExclusions([], [], null, ["임의 후보"]);
  const badDuplicate = { ...legacy, items: legacy.items.map(i => ({ ...i, state: "dismissed", duplicateOf: "not-present", resolutionReason: "중복" })) };
  assert.throws(() => editExclusions(legacy, badDuplicate, [], "owner"), { code: "INVALID_EXCLUSION" });
});
test("EXC-13/16~19: confirmed items survive proposals, safe public projection and immutable version carry", () => {
  const initial = prepareExclusions(sources, [], null);
  const confirmed = editExclusions(initial, confirm(initial), sources, "owner");
  const regenerated = prepareExclusions(sources, [], confirmed, [], ["외부 서비스 이용료 제외"]);
  assert.equal(regenerated.items.filter(i => i.state === "active").length, 5);
  assert.equal(regenerated.items.find(i => i.title === "외부 서비스 이용료 제외")?.origin, "ai_assumption");
  const title = confirmed.items.find(i => i.title.startsWith("관리자"))!.title;
  const snapshot = structuredClone(confirmed);
  const next = carryExclusions(confirmed, [title], "change-local", "고객 관리자 추가 승인", "owner")!;
  assert.equal(publicExclusions(next).length, 4); assert.deepEqual(confirmed, snapshot);
  assert.equal(next.items.find(i => i.title === title)?.state, "superseded");
  assert.ok(!JSON.stringify(publicExclusions(next)).includes("request:local"));
  const legacy = prepareExclusions([], [], null, ["명시되지 않은 추가 기능 / 외부 서비스 이용료"]);
  assert.equal(legacy.items[0].title, "명시되지 않은 추가 기능 / 외부 서비스 이용료");
  assert.equal(legacy.items[0].origin, "staff"); assert.equal(legacy.items[0].evidence.length, 0);
});
